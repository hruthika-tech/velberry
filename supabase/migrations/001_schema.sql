-- ═══════════════════════════════════════════════════════════════════════════
-- Velberry — PostgreSQL schema (Supabase)
-- Money is integer paise (₹1 = 100). Timestamps are timestamptz (stored UTC).
-- IDs are identity columns "by default", so migrated rows keep their original IDs.
-- Safe to re-run: every statement is IF NOT EXISTS.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists users (
  id            bigint generated by default as identity primary key,
  email         text not null,
  password_hash text not null,
  name          text not null,
  phone         text,
  role          text not null default 'customer' check (role in ('customer', 'admin')),
  created_at    timestamptz not null default now(),
  constraint users_email_lowercase check (email = lower(email))
);
create unique index if not exists users_email_key on users (lower(email));

create table if not exists sessions (
  token_hash text primary key,                       -- sha256 of the cookie token; the raw token is never stored
  user_id    bigint not null references users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists sessions_user_idx on sessions (user_id);
create index if not exists sessions_expiry_idx on sessions (expires_at);

create table if not exists addresses (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references users(id) on delete cascade,
  label      text,
  name       text not null,
  phone      text not null,
  line1      text not null,
  line2      text,
  city       text not null,
  state      text not null,
  pincode    text not null check (pincode ~ '^[1-9][0-9]{5}$'),
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists addresses_user_idx on addresses (user_id);

create table if not exists categories (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  name        text not null,
  description text,
  icon        text not null default 'heart',
  image_url   text,                                  -- optional photo in the category-images bucket
  sort_order  integer not null default 0
);

create table if not exists products (
  id            bigint generated by default as identity primary key,
  slug          text not null unique,
  name          text not null,
  category_id   bigint references categories(id) on delete set null,
  short_desc    text not null default '',
  description   text not null default '',
  materials     text not null default '',
  dimensions    text not null default '',
  price         integer not null check (price >= 0),
  compare_price integer check (compare_price is null or compare_price >= 0),
  stock         integer not null default 0 check (stock >= 0),   -- the database itself refuses to oversell
  sku           text,
  weight_grams  integer not null default 30 check (weight_grams > 0),
  is_active     boolean not null default true,
  is_featured   boolean not null default false,
  sold_out      boolean not null default false,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists products_category_idx on products (category_id);
create index if not exists products_active_idx on products (is_active, is_featured);

create table if not exists product_images (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  url        text not null,
  alt        text,
  kind       text not null default 'gallery' check (kind in ('gallery', 'angle')),
  sort_order integer not null default 0
);
create index if not exists product_images_product_idx on product_images (product_id, kind, sort_order);

create table if not exists product_variants (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  name       text not null,
  color_hex  text,
  price      integer check (price is null or price >= 0),
  stock      integer not null default 0 check (stock >= 0),
  sku        text,
  is_active  boolean not null default true,
  sort_order integer not null default 0
);
create index if not exists product_variants_product_idx on product_variants (product_id);

create table if not exists inventory_movements (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  variant_id bigint references product_variants(id) on delete set null,
  delta      integer not null,
  reason     text not null,                           -- reserve | release | cancel | restock | adjust
  order_id   bigint,
  created_at timestamptz not null default now()
);
create index if not exists inventory_movements_product_idx on inventory_movements (product_id, created_at);

create table if not exists carts (
  id          bigint generated by default as identity primary key,
  user_id     bigint unique references users(id) on delete cascade,
  guest_token text unique,
  updated_at  timestamptz not null default now()
);

create table if not exists cart_items (
  id         bigint generated by default as identity primary key,
  cart_id    bigint not null references carts(id) on delete cascade,
  product_id bigint not null references products(id) on delete cascade,
  variant_id bigint references product_variants(id) on delete cascade,
  quantity   integer not null check (quantity > 0),
  added_at   timestamptz not null default now()
);
create unique index if not exists cart_items_unique on cart_items (cart_id, product_id, coalesce(variant_id, 0));

create table if not exists orders (
  id                bigint generated by default as identity primary key,
  order_number      text not null unique,
  user_id           bigint references users(id) on delete set null,
  idempotency_key   text unique,
  access_token_hash text not null,
  status            text not null default 'pending_payment' check (status in (
                      'pending_payment', 'abandoned', 'paid', 'preparing', 'packed', 'ready_to_ship', 'shipped',
                      'out_for_delivery', 'delivered', 'delivery_failed', 'rto_initiated', 'rto_delivered', 'cancelled')),
  payment_status    text not null default 'pending' check (payment_status in ('pending', 'paid', 'failed', 'refunded', 'partially_refunded', 'expired')),
  customer_name     text not null,
  customer_email    text not null,
  customer_phone    text not null,
  ship_name         text not null,
  ship_phone        text not null,
  ship_line1        text not null,
  ship_line2        text,
  ship_city         text not null,
  ship_state        text not null,
  ship_pincode      text not null,
  subtotal          integer not null check (subtotal >= 0),
  shipping_fee      integer not null check (shipping_fee >= 0),
  total             integer not null check (total >= 0),
  gift_note         text,
  stock_reserved    boolean not null default true,
  razorpay_order_id text unique,
  expires_at        timestamptz,
  paid_at           timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index if not exists orders_status_idx on orders (status);
create index if not exists orders_created_idx on orders (created_at desc);
create index if not exists orders_user_idx on orders (user_id);
create index if not exists orders_email_idx on orders (lower(customer_email));
create index if not exists orders_pending_expiry_idx on orders (expires_at) where status = 'pending_payment';

-- Historical snapshot: names, prices and images as they were at purchase time.
create table if not exists order_items (
  id           bigint generated by default as identity primary key,
  order_id     bigint not null references orders(id) on delete cascade,
  product_id   bigint references products(id) on delete set null,
  variant_id   bigint references product_variants(id) on delete set null,
  product_name text not null,
  variant_name text,
  sku          text,
  image_url    text,
  unit_price   integer not null check (unit_price >= 0),
  quantity     integer not null check (quantity > 0),
  line_total   integer not null check (line_total >= 0)
);
create index if not exists order_items_order_idx on order_items (order_id);
create index if not exists order_items_product_idx on order_items (product_id);

create table if not exists order_status_history (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references orders(id) on delete cascade,
  from_status text,
  to_status   text not null,
  note        text,
  actor       text not null default 'system',
  created_at  timestamptz not null default now()
);
create index if not exists order_status_history_order_idx on order_status_history (order_id, id);

create table if not exists payments (
  id                  bigint generated by default as identity primary key,
  order_id            bigint not null references orders(id) on delete cascade,
  provider            text not null default 'razorpay',
  provider_order_id   text,
  provider_payment_id text not null unique,          -- one row per Razorpay payment: duplicates are impossible
  status              text not null,                 -- captured | authorized | failed
  method              text,
  amount              integer not null check (amount >= 0),
  error_reason        text,
  raw                 jsonb,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index if not exists payments_order_idx on payments (order_id);

create table if not exists refunds (
  id                 bigint generated by default as identity primary key,
  order_id           bigint not null references orders(id) on delete cascade,
  payment_id         bigint not null references payments(id),
  provider_refund_id text unique,
  amount             integer not null check (amount > 0),
  status             text not null check (status in ('pending', 'processed', 'failed')),
  reason             text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists refunds_order_idx on refunds (order_id);

create table if not exists shipments (
  id                   bigint generated by default as identity primary key,
  order_id             bigint not null unique references orders(id) on delete cascade,
  provider             text not null check (provider in ('shiprocket', 'manual')),
  provider_order_id    text,
  provider_shipment_id text,
  awb_code             text,
  courier_name         text,
  courier_id           text,
  status               text not null default 'created',
  pickup_scheduled_at  text,                           -- as reported by the courier (free-form date text)
  etd                  text,
  tracking_url         text,
  label_url            text,
  last_synced_at       timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index if not exists shipments_awb_idx on shipments (awb_code);

create table if not exists tracking_events (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references orders(id) on delete cascade,
  shipment_id bigint references shipments(id) on delete cascade,
  status      text not null,
  description text,
  location    text,
  occurred_at text not null,                          -- courier-supplied timestamp, kept verbatim
  source      text not null,
  dedupe_key  text not null unique
);
create index if not exists tracking_events_order_idx on tracking_events (order_id);

-- Email log: one row per message, with delivery status and provider reference.
create table if not exists notifications (
  id          bigint generated by default as identity primary key,
  order_id    bigint references orders(id) on delete cascade,
  type        text not null,
  channel     text not null default 'email',
  recipient   text not null,
  subject     text not null,
  status      text not null check (status in ('pending', 'sent', 'failed', 'logged')),
  provider_id text,
  error       text,
  created_at  timestamptz not null default now()
);
-- each (order, type) email is sent at most once (failed attempts may be retried)
create unique index if not exists notifications_once on notifications (order_id, type) where status <> 'failed';
create index if not exists notifications_created_idx on notifications (created_at desc);

create table if not exists webhook_events (
  id          bigint generated by default as identity primary key,
  provider    text not null,
  event_id    text not null,
  event_type  text,
  payload     jsonb,
  received_at timestamptz not null default now(),
  unique (provider, event_id)
);

create table if not exists settings (
  key   text primary key,
  value text not null
);
