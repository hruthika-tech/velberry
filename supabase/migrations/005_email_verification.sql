-- CLAYSLAY — email verification
--
--  • users.email_verified_at: when the customer clicked the link in their verification email (NULL = not yet).
--    Existing accounts are left unverified (nothing is back-filled); they can ask for a link from their account.
--    Verification does not gate shopping — the site only reminds unverified customers.
--  • email_verifications: one row per link sent. Only the sha256 of the token is stored (like sessions), so a
--    database read can never be turned into a working link. Rows are single-use (deleted once the email is
--    verified) and expire after 24 hours.
--
-- Additive only: no existing row or column changes, so it is safe to apply before the code that uses it.
-- Access: private, like users/sessions — RLS on, no policies, and the public API roles hold no grants.
-- Safe to re-run.
-- ═══════════════════════════════════════════════════════════════════════════

alter table users add column if not exists email_verified_at timestamptz;

create table if not exists email_verifications (
  id          bigint generated by default as identity primary key,
  token_hash  text not null unique,                    -- sha256 of the emailed token; the raw token is never stored
  user_id     bigint not null references users(id) on delete cascade,
  expires_at  timestamptz not null,
  created_at  timestamptz not null default now()
);
create index if not exists email_verifications_user_idx on email_verifications (user_id, created_at desc);
create index if not exists email_verifications_expiry_idx on email_verifications (expires_at);

alter table email_verifications enable row level security;
revoke all on table email_verifications from public;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on table email_verifications from anon, authenticated;
  end if;
end $$;
